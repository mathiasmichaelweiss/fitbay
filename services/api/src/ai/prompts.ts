/* ---- коуч на день ---- */
export interface CoachCtx {
  profile: { sex: string; age: number; h: number; w: number; tw?: number; act: number; goal: string };
  target: Target;
  day: string;
  /** «14:30» или «день уже прошел» */
  now: string;
  workoutToday: string;
  meals: MealT[];
  week: string;
  lang: string;
}
const GOAL_NAME: Record<string, string> = {
  lose: 'похудение',
  recomp: 'рекомпозиция (сбросить жир, сохранить мышцы, силовые тренировки)',
  keep: 'удержание веса',
  gain: 'набор мышечной массы',
};
const hhmm = (ts: number) => new Date(ts).toLocaleTimeString('ru-RU', { hour: '2-digit', minute: '2-digit', timeZone: 'Europe/Berlin' });

export function coachPrompt(c: CoachCtx): string {
  const p = c.profile, t = c.target;
  const s = c.meals.reduce((a, m) => ({ k: a.k + m.kcal, p: a.p + m.protein, f: a.f + m.fat, c: a.c + m.carbs }), { k: 0, p: 0, f: 0, c: 0 });
  const groups = groupMeals(c.meals, t.k);
  const sl: Record<string, string> = {};
  groups.forEach((g) => g.items.forEach((m) => (sl[m.id] = g.slot)));
  const eaten = [...c.meals]
    .sort((x, y) => x.ts - y.ts)
    .map((m) => `${hhmm(m.ts)} [${(SLOTN[sl[m.id] as keyof typeof SLOTN] || 'приём пищи').toLowerCase()}] ${m.name}${m.desc ? ` (${String(m.desc).slice(0, 140)})` : ''}: ${m.kcal} ккал, Б ${m.protein}, Ж ${m.fat}, У ${m.carbs}`)
    .join('\n');
  const done = [...new Set(groups.map((g) => g.slot))].filter((x) => x !== 'snack');
  const doneTxt = done.length
    ? `Уже были: ${done.map((x) => SLOTN[x].toLowerCase()).join(', ')}. ВАЖНО: не советуй приём пищи, который уже был. Если ужин уже был, не говори «на ужин» и «ужин должен быть лёгким»: предложи максимум небольшой перекус, если он реально нужен (например, для белка), или скажи, что на сегодня еды достаточно.`
    : '';
  return `Ты персональный коуч по питанию и строгий, но поддерживающий тренер. Твоя работа говорить правду, а не утешать. Ты не хвалишь то, что не заслуживает похвалы, и не смягчаешь ошибки. Если в приеме пищи мало белка, много сахара или быстрых углеводов, или он съел большую долю дневной нормы калорий, прямо назови это с цифрами. Тон уважительный, без морали и запугивания, как тренер, который на стороне клиента и хочет результата.
Профиль: ${p.sex === 'm' ? 'мужчина' : 'женщина'}, ${p.age} лет, ${p.h} см, ${p.w} кг, цель по весу ${p.tw || p.w} кг, тренировок в неделю: ${p.act}. Цель: ${GOAL_NAME[p.goal]}.
Норма на день: ${t.k} ккал, белок ${t.p} г, жиры ${t.f} г, углеводы ${t.c} г.
Дата: ${c.day}, сейчас: ${c.now}.
Тренировка в этот день: ${c.workoutToday}. Если тренировка была, учитывай, что после силовой важны белок и достаточное количество углеводов для восстановления.
Съедено за день (по порядку, в скобках приём пищи, как он отмечен в приложении):
${eaten || 'пока ничего'}
${doneTxt}
Итого: ${s.k} ккал, Б ${s.p}, Ж ${s.f}, У ${s.c}.
Последние 7 дней:
${c.week || 'нет данных'}
Задача: напиши сообщение так, как его написал бы живой опытный тренер своему клиенту в мессенджере. Не шаблон и не отчет, а человеческая речь: разные по длине предложения, естественные связки, можно легкий юмор или разговорные слова, но без панибратства. Обращайся на «ты». Объем 3-5 предложений, примерно 50-90 слов.
Что должно быть внутри, но в свободной форме, а не по пунктам: честно скажи, что сегодня получилось хорошо, а что нет (одна-две цифры максимум, только самые важные); если есть косяк, не смягчай его, но и не читай нотаций; предложи одну-две конкретные человеческие идеи, что съесть дальше, с названием блюда (например: «вечером сделай омлет из трех яиц с творогом» или «возьми греческий йогурт с горстью орехов»), учитывая, сколько калорий у него осталось.
Запрещено: штампы вроде «Ты на правильном пути», «Держи темп», «Отличная работа», «Слушай,» в начале; псевдонаучные фразы (например, что сахар «рассеивает энергию» или «мешает телу сосредоточиться на жире»), говори только то, что реально верно с точки зрения диетологии; перечисление остатков калорий, жиров и углеводов; граммовки по каждому приему пищи; оценка времени приемов пищи (у всех разный режим); советы на завтра, пока день еще идет; списки, заголовки, длинное тире.
Если за неделю видишь повторяющийся паттерн, можешь упомянуть его одной фразой. Отвечай ${inLang(c.lang)}.`;
}

