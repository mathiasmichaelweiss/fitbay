/* ---- блюдо из книги: сколько грамм съел (recAI прототипа) ---- */
export function foodPortionPrompt(r: { name: string; desc?: string; grams?: number }, said: string, plate: FoodInput['plate']): string {
  const np = !plate || plate.type === 'none';
  const pl = np
    ? 'посуда неизвестна'
    : `посуда: ${TYPES.find((x) => x.k === plate!.type)?.n ?? ''}, размер ${SIZES[plate!.type]?.find((x) => x[0] === plate!.size)?.[1] ?? ''}, заполнена: ${FILLS.find((x) => x[0] === plate!.fill)?.[1] ?? ''}`;
  return `Оцени, сколько грамм этого блюда человек съел.
Блюдо из его книги рецептов: ${r.name}. Состав: ${r.desc || 'не указан'}. Его обычная порция: ${r.grams || 'неизвестна'} г.
Что он написал про этот прием пищи: ${said || 'ничего'}.
${pl}.
Если информации мало, ориентируйся на обычную порцию. Ответь только JSON: {"grams":число}`;
}

