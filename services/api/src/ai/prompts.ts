import { groupMeals, SLOTN, type MealT, type Target } from '@fitbay/calc';

const inLang = (lang: string) => (lang === 'de' ? 'на немецком' : 'по-русски');

/* ---- оценка блюда по фото / тексту ---- */
export const TYPES = [
  { k: 'flat', n: 'Плоская' },
  { k: 'deep', n: 'Глубокая' },
  { k: 'bowl', n: 'Миска' },
  { k: 'box', n: 'Контейнер' },
] as const;
export const SIZES: Record<string, [string, string][]> = {
  flat: [['S', '20 см'], ['M', '24 см'], ['L', '28 см']],
  deep: [['S', '18 см'], ['M', '22 см'], ['L', '26 см']],
  bowl: [['S', '300 мл'], ['M', '500 мл'], ['L', '800 мл']],
  box: [['S', '500 мл'], ['M', '750 мл'], ['L', '1 л']],
};
export const FILLS: [string, string][] = [['quarter', 'Четверть'], ['half', 'Половина'], ['full', 'Полная'], ['heap', 'С горкой']];

export interface FoodInput {
  dish?: string;
  desc?: string;
  /** Посуда: type (flat|deep|bowl|box) или none, размер S|M|L, заполненность. */
  plate?: { type: string; size?: string; fill?: string } | null;
  grams?: number | null;
  hasImage: boolean;
  lang: string;
}

export function foodPrompt(i: FoodInput, communityHint: string, personalHint: string): string {
  const np = !i.plate || i.plate.type === 'none';
  const t = np ? '' : TYPES.find((x) => x.k === i.plate!.type)?.n ?? '';
  const sz = np ? '' : SIZES[i.plate!.type]?.find((x) => x[0] === i.plate!.size)?.[1] ?? '';
  const fl = np ? '' : FILLS.find((x) => x[0] === i.plate!.fill)?.[1] ?? '';
  const L = inLang(i.lang);
  return `Ты нутрициолог. Оцени калорийность и БЖУ одной порции.
Блюдо: ${i.dish || '(не указано, определи по фото)'}
Описание (может быть надиктовано голосом, возможны ошибки распознавания): ${i.desc?.trim() || 'нет'}
${np ? 'Посуда и размер неизвестны: возьми типичную стандартную порцию такого блюда, как его обычно подают или готовят дома (например, один круассан среднего размера, ломтик хамона, одно яйцо), и оцени вес каждого ингредиента сам.' : `Посуда: ${t}, размер ${sz}, заполнена: ${fl}.`}
Вес от пользователя: ${i.grams || 'неизвестен'} г.
${i.hasImage ? 'Фото приложено, используй его для оценки состава и объема.' : 'Фото нет.'}
Как оценивать вес по фото, по шагам:
1) Масштаб. Найди на фото предметы известного размера: ладонь взрослого 8-9 см в ширину, палец 2 см, вилка 19-20 см, чайная ложка 13-15 см, столовая тарелка 25-27 см, десертная 19-21 см, маленькая блюдце/пиалка 12-15 см, телефон 15 см. Если посуда лежит на ладони и почти не выходит за неё, это МАЛЕНЬКАЯ посуда (12-15 см), а не обычная тарелка.
2) Размеры еды в сантиметрах относительно этого масштаба, затем объём в см³. Люди почти всегда ПЕРЕоценивают размеры: еда в руке ближе к камере и кажется больше, поэтому сравнивай кусок прямо с шириной пальца (2 см) и ладони, а итоговые размеры уменьши на 15-20%.
3) Плотность по типу блюда (г/см³), строго в этих пределах, не выше: бисквит, кекс, Sandkuchen, Rührkuchen, Marmorkuchen, песочный и масляный кекс, пирог из теста, маффин 0,3-0,4 (пористые, весят мало!); хлеб 0,25-0,4; булочки, круассан 0,15-0,3; торт с кремом 0,5-0,7; чизкейк 0,9-1,0; мясо, рыба 1,0; каша, рис, макароны 0,8-1,0; салат из листьев 0,15-0,3; суп 1,0. Вес = объём × плотность.
4) Сверь с типичным куском: один кусок кекса 25-50 г, ломтик хлеба 25-35 г. Лучше чуть недооценить пористую выпечку, чем переоценить.
${communityHint}
${personalHint}
Оцени объем по посуде и заполненности, затем вес, затем калории. ОБЯЗАТЕЛЬНО учти каждый ингредиент из названия и описания, ничего не пропускай, даже ложку соуса, масла или пасты. Если вес указан, это общий вес порции: распредели его между всеми ингредиентами.
Ответь только JSON: {"name":"короткое название ${L}","names":["3 разных варианта красивого короткого названия блюда ${L}, 2-5 слов, без веса и граммов"],"grams":число,"kcal":число,"protein":число,"fat":число,"carbs":число,"confidence":"низкая|средняя|высокая","note":"${L}: одно короткое предложение, как оценивал порцию","items":[{"n":"ингредиент ${L}","g":граммы,"kcal":число,"p":белок,"f":жиры,"c":углеводы}]}
В items распиши КАЖДЫЙ ингредиент отдельно; grams, kcal, protein, fat, carbs должны быть суммой items.`;
}

