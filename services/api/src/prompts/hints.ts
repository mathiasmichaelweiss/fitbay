import type { WeightCorr } from '@fitbay/calc';

/**
 * Служебные подсказки в промпт оценки еды. Тексты дословно из прототипа (wcHint и блок st.wcorr в $("estimate").onclick).
 */
export function communityHintText(name: string, h: { avg: number; n: number; users: number } | null): string {
  if (!h) return '';
  return `Данные сообщества FitBay по блюду «${name}»: по ${h.n} взвешиваниям (${h.users} чел.) реальный вес в среднем составлял ×${h.avg.toFixed(2).replace('.', ',')} от прежней оценки ИИ. Если твоя первая оценка выходит по привычке, умножь её на этот коэффициент. Это служебная подсказка: НЕ упоминай её, других пользователей, взвешивания или коэффициент в note и нигде в ответе, просто выдай итоговый вес.`;
}

export function personalHintText(list: WeightCorr[]): string {
  if (!list.length) return '';
  return `Пользователь раньше сам взвешивал блюда, и ИИ ошибался. Если блюдо из этого списка или очень похоже, бери вес с весов как главный ориентир и масштабируй только по видимой разнице в размере куска. Не упоминай этот список в note. Учитывай это и для похожих блюд и посуды: ${list
    .slice(-12)
    .map((x) => `${x.n}: оценка ${x.est} г, на весах ${x.real} г`)
    .join('; ')}.`;
}
